import logging

from fastapi import APIRouter, Depends

from app.errors import ApiError
from app.schemas.ai import AskData, AskRequest, InsightData
from app.schemas.common import Envelope
from app.services import ai, ask, data, insights, sql_guard
from app.services.filters import Filters, common_filters
from app.services.meta import build_meta

log = logging.getLogger("app.ai")
router = APIRouter(prefix="/api", tags=["ai"])


@router.get("/insights", response_model=Envelope[InsightData], summary="Insight cards: facts computed in Python, phrased by Claude")
def insights_view(state: str | None = None, f: Filters = Depends(common_filters)):
    year = f.year or data.latest_year()
    if state:
        state = state.strip().upper()
        if state not in set(data.frames().states.state_code):
            raise ApiError(422, "unknown_state", f"Unknown state code(s): {state}")
    cards, info = insights.insights(year, state, f.include_synthetic, ai.available())
    notes = ["Every number comes from the dataset; Claude only rephrases the computed facts and any sentence containing a number "
             "outside its facts is replaced by the template sentence."]
    if info["ai_note"]:
        notes.append(info["ai_note"])
    if info["rejected"]:
        notes.append(f"{info['rejected']} Claude sentence(s) were rejected by the number check and replaced by templates.")
    if not cards:
        notes.append("not_available: no data for this selection")
    return {"data": {"year": year, "state": state, "phrasing": info["phrasing"], "cards": cards},
            "meta": build_meta(f, ["tourism_annual", "tourism_monthly"], [c["is_synthetic"] for c in cards], notes,
                               resolved={"year": year})}


@router.post("/ask", response_model=Envelope[AskData], summary="Natural-language question -> validated read-only SQL -> data")
def ask_view(body: AskRequest):
    if not ai.available():
        raise ApiError(503, "ai_not_configured",
                       "The /api/ask endpoint needs ANTHROPIC_API_KEY to translate questions into SQL. "
                       "Set it in the environment (see .env.example); all other endpoints work without it.")
    try:
        r = ask.answer(body.question.strip())
    except ai.AiUnavailable as e:
        raise ApiError(503, "ai_not_configured", str(e)) from e
    except ai.AiError as e:
        raise ApiError(502, "ai_error", f"The AI service failed: {e}") from e
    except sql_guard.SqlRejected as e:
        raise ApiError(422, "sql_rejected", f"The generated query was rejected: {e}") from e
    except sql_guard.QueryTimeout as e:
        raise ApiError(408, "query_timeout", str(e)) from e
    notes = ["SQL was generated by Claude from the dataset schema, validated (single SELECT, whitelisted tables/columns/functions) "
             "and executed read-only with a row limit and timeout."]
    if r["truncated"]:
        notes.append("Result truncated to the row limit.")
    meta = {"filters": {"question": r["question"]}, "data_sources": r["sources"], "synthetic_share": r["synthetic_share"],
            "record_count": r["row_count"], "notes": notes}
    d = {k: r[k] for k in AskData.model_fields}
    return {"data": d, "meta": meta}
