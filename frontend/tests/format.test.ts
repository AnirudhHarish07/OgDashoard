import { describe, expect, it } from 'vitest';
import { escapeHtml, formatCount, formatCrore, formatMetric, formatNumber, formatPct, formatRupees, groupIndian, preferDisplay, shortSource, splitDisplay } from '@/lib/format';

describe('Indian number formatting', () => {
  it('groups digits the Indian way', () => {
    expect(groupIndian(12345678)).toBe('1,23,45,678');
    expect(groupIndian(1234)).toBe('1,234');
    expect(groupIndian(100)).toBe('100');
    expect(groupIndian(-9876543.5, 1)).toBe('-98,76,543.5');
    expect(groupIndian(0)).toBe('0');
  });
  it('formats visit counts in lakh and crore', () => {
    expect(formatCount(219_000_000)).toBe('21.9 Cr');
    expect(formatCount(30_500_000)).toBe('3.05 Cr');
    expect(formatCount(305_000)).toBe('3.05 L');
    expect(formatCount(4_300_000)).toBe('43.0 L');
    expect(formatCount(45_210)).toBe('45,210');
    expect(formatCount(null)).toBeNull();
    expect(formatCount(Number.NaN)).toBeNull();
  });
  it('formats money in crore, lakh crore and rupees', () => {
    expect(formatCrore(9713.89)).toBe('₹9,714 Cr');
    expect(formatCrore(1_027_314.88)).toBe('₹10.3 L Cr');
    expect(formatRupees(2536)).toBe('₹2,536');
    expect(formatRupees(undefined)).toBeNull();
  });
  it('formats percentages and per-metric values', () => {
    expect(formatPct(14.39, true)).toBe('+14.4%');
    expect(formatPct(-2.1, true)).toBe('-2.1%');
    expect(formatPct(55.5)).toBe('55.5%');
    expect(formatNumber(6501.4)).toBe('6,501');
    expect(formatMetric('revenue', 1500)).toBe('₹1,500 Cr');
    expect(formatMetric('growth_pct', 12)).toBe('+12.0%');
    expect(formatMetric('total_visits', 12_000_000)).toBe('1.20 Cr');
  });
  it('prefers the backend display string and falls back to the formatter', () => {
    expect(preferDisplay('21.9 Cr', 5)).toBe('21.9 Cr');
    expect(preferDisplay(null, 219_000_000)).toBe('21.9 Cr');
    expect(preferDisplay(undefined, null)).toBe('n/a');
    expect(preferDisplay(null, 1500, formatCrore)).toBe('₹1,500 Cr');
  });
  it('splits display strings for the count-up animation', () => {
    expect(splitDisplay('287.0 Cr')).toEqual({ prefix: '', value: 287, decimals: 1, suffix: ' Cr', grouped: false });
    expect(splitDisplay('₹9,714 Cr')).toMatchObject({ prefix: '₹', value: 9714, decimals: 0, suffix: ' Cr', grouped: true });
    expect(splitDisplay('+14.4%')).toMatchObject({ prefix: '+', value: 14.4, suffix: '%' });
    expect(splitDisplay('n/a')).toBeNull();
  });
  it('shortens source strings and escapes html', () => {
    expect(shortSource('SYNTHETIC: generated by src/synthesize.py (seed=42); illustrative')).toBe('SYNTHETIC (src/synthesize.py)');
    expect(shortSource(undefined)).toBe('unknown');
    expect(escapeHtml('<b>"x" & y</b>')).toBe('&lt;b&gt;&quot;x&quot; &amp; y&lt;/b&gt;');
  });
});
